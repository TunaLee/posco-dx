T = "1-3"
EX = Path(__file__).resolve().parent.parent / "labs" / "room_booking" / "예시"


def _plan():
    return (EX / "기획서.md").read_text(encoding="utf-8").strip()


def _sec(name):
    """기획서.md 의 「## name」 칸을 제목 줄과 함께 그대로."""
    t = _plan()
    i = t.index(f"## {name}")
    j = t.find("\n## ", i + 1)
    return t[i: j if j > 0 else None].strip()


def _heads():
    return "\n".join(x for x in _plan().split("\n") if x.startswith("#"))


def _cell(title, name, qs, nt):
    """칸 한 장 — 왼쪽 기획서.md 의 그 칸 · 오른쪽 쓰는 질문."""
    return light(title, '<div class="twocol"><div>' + code("기획서.md · 예", esc(_sec(name)))
                 + '</div><div>' + viz2.tiles(qs, 1) + "</div></div>" + note(*nt), T)



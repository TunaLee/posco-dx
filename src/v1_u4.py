def _prd():
    return (EX / "PRD.md").read_text(encoding="utf-8").strip()


def _sec(no):
    """PRD.md 의 「## no.」 칸을 제목 줄과 함께 그대로."""
    t = _prd()
    i = t.index(f"## {no}.")
    j = t.find("\n## ", i + 1)
    return t[i: j if j > 0 else None].strip()


def _cell(title, no, qs, nt):
    return light(title, '<div class="twocol"><div>' + code("PRD.md · 예", esc(_sec(no)))
                 + '</div><div>' + viz2.tiles(qs, 1) + "</div></div>" + note(*nt), T)


